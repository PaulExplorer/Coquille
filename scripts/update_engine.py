#!/usr/bin/env python3
"""Copy a fresh Grammalecte engine build into this repository.

The engine is never modified here: this script packages the artifacts produced
by the upstream build (``make.py fr -js``) into the layout expected by the
extension. To update the engine:

1. Obtain an up-to-date Grammalecte source tree yourself (an archive or a git
   checkout of a mirror). This script never fetches anything over the network.
2. Run::

       python3 scripts/update_engine.py --from /path/to/grammalecte

3. Review the diff under ``src/engine/grammalecte/`` and ``public/grammalecte/``
   and commit it.

Outputs:
- ``src/engine/grammalecte/``      JavaScript engine files, copied verbatim.
- ``src/engine/grammalecte/_generated/engine_bundle.js``
                                   concatenation of the engine files in the
                                   same order as upstream's ``gce_worker.js``
                                   import list, exported at the end.
- ``public/grammalecte/``          JSON data files (conjugation, morphology,
                                   dictionaries) fetched at runtime.
- ``public/grammalecte/ENGINE_VERSION.json``
                                   provenance record of the vendored build.
"""

from __future__ import annotations

import argparse
import datetime
import json
import pathlib
import re
import shutil
import subprocess
import sys

REPO_ROOT = pathlib.Path(__file__).resolve().parent.parent
ENGINE_DEST = REPO_ROOT / "src" / "engine" / "grammalecte"
DATA_DEST = REPO_ROOT / "public" / "grammalecte"

# Data files passed at runtime to the engine glue. thesaurus data is heavy
# (about 6 MB) and only needed for the thesaurus feature, which we do not
# ship in v1, so it is not copied.
JSON_DATA_FILES = [
    "fr/conj_data.json",
    "fr/mfsp_data.json",
    "fr/phonet_data.json",
]
DICTIONARY_FILES = ["graphspell/_dictionaries/fr-allvars.json"]

# Symbols exported by the generated bundle and consumed by the extension glue.
# Keep in sync with EngineBundleExports in src/engine/glue/bundle-contract.ts.
EXPORTED_SYMBOLS = [
    "helpers",
    "text",
    "Tokenizer",
    "SpellChecker",
    "IBDAWG",
    "conj",
    "phonet",
    "mfsp",
    "thesaurus",
    "gc_engine",
    "gc_functions",
    "gc_options",
]

# TypeScript declarations generated next to the bundle, wired to the structural
# contract maintained by the extension (src/engine/glue/bundle-contract.ts).
BUNDLE_D_TS = """// GENERATED FILE - DO NOT EDIT.
// Type surface of the generated engine bundle; regenerated by
// scripts/update_engine.py. All detailed types live in the bundle contract.
import type { EngineBundleExports } from "../../glue/bundle-contract";

export declare const helpers: EngineBundleExports["helpers"];
export declare const text: EngineBundleExports["text"];
export declare const Tokenizer: EngineBundleExports["Tokenizer"];
export declare const SpellChecker: EngineBundleExports["SpellChecker"];
export declare const IBDAWG: EngineBundleExports["IBDAWG"];
export declare const conj: EngineBundleExports["conj"];
export declare const phonet: EngineBundleExports["phonet"];
export declare const mfsp: EngineBundleExports["mfsp"];
export declare const thesaurus: EngineBundleExports["thesaurus"];
export declare const gc_engine: EngineBundleExports["gc_engine"];
export declare const gc_functions: EngineBundleExports["gc_functions"];
export declare const gc_options: EngineBundleExports["gc_options"];
"""



def fail(message: str) -> None:
    raise SystemExit(f"error: {message}")


def run_make(grammalecte_dir: pathlib.Path) -> None:
    if not (grammalecte_dir / "make.py").exists():
        fail(f"not a Grammalecte source tree (no make.py found in {grammalecte_dir})")
    print(f"Building Grammalecte JS engine in {grammalecte_dir} ...")
    result = subprocess.run(
        [sys.executable, "make.py", "fr", "-js"],
        cwd=grammalecte_dir,
    )
    if result.returncode != 0:
        fail("'make.py fr -js' failed")
    if not (grammalecte_dir / "grammalecte-js").is_dir():
        fail("build did not produce a grammalecte-js directory")


def read_import_order(grammalecte_dir: pathlib.Path) -> list[str]:
    """Parse the importScripts() list of upstream gce_worker.js."""
    worker = grammalecte_dir / "gc_lang" / "fr" / "webext" / "gce_worker.js"
    if not worker.exists():
        fail(f"cannot find {worker} in the source tree")
    imports: list[str] = []
    for match in re.finditer(r'importScripts\("([^"]+)"\)', worker.read_text(encoding="utf-8")):
        path = match.group(1)
        if path.endswith("tests.js"):
            continue  # test harness, only used by upstream's full test suite
        imports.append(path)
    if not imports:
        fail("no importScripts() entries found in gce_worker.js")
    return imports


def clean_directory(path: pathlib.Path) -> None:
    if path.exists():
        shutil.rmtree(path)
    path.mkdir(parents=True)


def copy_engine_files(
    grammalecte_out: pathlib.Path,
    imports: list[str],
    js_dest: pathlib.Path,
) -> None:
    clean_directory(js_dest)
    generated_dir = js_dest / "_generated"
    generated_dir.mkdir()
    bundle_parts: list[str] = []
    for imported in imports:
        # importScripts paths are relative to the web extension root, where the
        # build output sits under a "grammalecte/" prefix.
        relative = imported.removeprefix("grammalecte/")
        source = grammalecte_out / relative
        if not source.exists():
            fail(f"engine file listed in gce_worker.js is missing: {relative}")
        destination = js_dest / relative
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, destination)
        bundle_parts.append(f"// --- engine file: {relative} ---\n{source.read_text(encoding='utf-8')}")

    exports = ", ".join(EXPORTED_SYMBOLS)
    bundle = (
        "// GENERATED FILE - DO NOT EDIT.\n"
        "// Concatenation of the Grammalecte engine JavaScript files, in the import\n"
        "// order declared by upstream's gce_worker.js. Regenerated by\n"
        "// scripts/update_engine.py. The engine files as vendored verbatim live in\n"
        "// the sibling directories of this one.\n"
        "\n"
        + "\n\n".join(bundle_parts)
        + "\n\nexport {\n"
        + "".join(f"  {symbol},\n" for symbol in EXPORTED_SYMBOLS)
        + "};\n"
    )
    (generated_dir / "engine_bundle.js").write_text(bundle, encoding="utf-8")

    # Upstream keep CommonJS fallbacks gated on `typeof(process)` (Node only).
    # They are dead code in a browser, but bundlers resolve every specifier
    # statically, so companion stub modules are required here for the build.
    writes_stub_modules(generated_dir, resolve_stub_targets(bundle))
    (generated_dir / "engine_bundle.d.ts").write_text(BUNDLE_D_TS, encoding="utf-8")
    (generated_dir / "README.md").write_text(
        "# Generated engine bundle\n\n"
        "This directory is produced by `scripts/update_engine.py` from the "
        "Grammalecte source tree. Do not edit by hand.\n",
        encoding="utf-8",
    )


def resolve_stub_targets(bundle_source: str) -> list[str]:
    """Relative `require("./x.js")` specifiers used by the CommonJS branches."""
    targets: set[str] = set()
    for specifiers in re.findall(r'require\("([^"]+)"\)', bundle_source):
        if re.match(r"^\.{1,2}/[\w\-.]+\.js$", specifiers):
            targets.add(specifiers)
    return sorted(targets)


def writes_stub_modules(generated_dir: pathlib.Path, targets: list[str]) -> None:
    for specifier in targets:
        file_name = pathlib.Path(specifier).name
        stub = (
            "// Generated stub - DO NOT EDIT.\n"
            "// The engine carries CommonJS fallback branches (Node-only, dead\n"
            "// code in a browser). Bundlers still resolve their require() calls\n"
            "// statically; this stub only satisfies that resolution.\n"
            "export {};\n"
        )
        (generated_dir / file_name).write_text(stub, encoding="utf-8")


def copy_data_files(grammalecte_out: pathlib.Path, data_dest: pathlib.Path) -> None:
    clean_directory(data_dest)
    for relative in [*JSON_DATA_FILES, *DICTIONARY_FILES]:
        source = grammalecte_out / relative
        if not source.exists():
            fail(f"data file missing from the build output: {relative}")
        destination = data_dest / relative
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_bytes(source.read_bytes())


def write_provenance(grammalecte_dir: pathlib.Path, data_dest: pathlib.Path) -> None:
    config = grammalecte_dir / "gc_lang" / "fr" / "config.ini"
    config_text = config.read_text(encoding="utf-8", errors="replace") if config.exists() else ""
    version_match = re.search(r"^version\s*=\s*(\S+)", config_text, flags=re.MULTILINE)
    if version_match is None:
        fail("cannot read the engine version from gc_lang/fr/config.ini")
    provenance = {
        "engineVersion": version_match.group(1),
        "sourcePath": str(grammalecte_dir),
        "packagedAt": datetime.datetime.now(datetime.timezone.utc)
        .replace(microsecond=0)
        .isoformat()
        .replace("+00:00", "Z"),
    }
    (data_dest / "ENGINE_VERSION.json").write_text(
        json.dumps(provenance, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description="Update the vendored Grammalecte engine.")
    parser.add_argument(
        "--from",
        dest="source",
        required=True,
        help="path to a Grammalecte source tree (the script never fetches anything itself)",
    )
    parser.add_argument(
        "--skip-build",
        action="store_true",
        help="reuse the existing grammalecte-js build output instead of running make.py",
    )
    args = parser.parse_args()

    source = pathlib.Path(args.source).resolve()
    print(f"Using Grammalecte source tree: {source}")
    if not args.skip_build:
        run_make(source)
    output = source / "grammalecte-js"
    if not output.is_dir():
        fail("grammalecte-js directory not found; run the build first")
    imports = read_import_order(source)

    print(f"Copying engine JS files to {ENGINE_DEST.relative_to(REPO_ROOT)} and generating the bundle ...")
    copy_engine_files(output, imports, ENGINE_DEST)
    print(f"Copying data files to {DATA_DEST.relative_to(REPO_ROOT)} ...")
    copy_data_files(output, DATA_DEST)
    write_provenance(source, DATA_DEST)
    print("Done. Review the diff and commit:", file=sys.stderr)
    print("  git add src/engine/grammalecte public/grammalecte", file=sys.stderr)
    print(f"  git commit -m 'Update vendored Grammalecte engine ({json.loads((DATA_DEST / 'ENGINE_VERSION.json').read_text())['engineVersion']})'", file=sys.stderr)


if __name__ == "__main__":
    main()
